def run(*argv):
    """(exit code, stdout + stderr) of `nju-connect ARGV`, without colors."""
    out = io.StringIO()
    env = {k: v for k, v in os.environ.items() if k not in ("FORCE_COLOR", "PYTHON_COLORS")}
    env.update(NO_COLOR="1", COLUMNS="100")
    with mock.patch.dict(os.environ, env, clear=True), redirect_stdout(out), redirect_stderr(out):
        try:
            args = cli.build_parser().parse_args(list(argv))
            args.func(args)
            code = 0
        except SystemExit as e:
            code = e.code or 0
    return code, out.getvalue()


class HelpTest(ExportFixture):
    def test_each_format_has_its_own_help(self):
        code, text = run("export", "xray", "-h")
        self.assertEqual(code, 0)
        self.assertIn("usage: nju-connect export xray", text)
        self.assertIn("restarts Xray", text)
