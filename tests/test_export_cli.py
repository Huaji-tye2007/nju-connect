class UnwritableInstallTest(ExportFixture):
    def setUp(self):
        super().setUp()
        if os.getuid() == 0:
            self.skipTest("root can write anywhere")
        self.conf = self.tmp / "config.json"
        self.conf.write_text(SING_BOX_CONFIG)
        os.chmod(self.conf, 0o444)
        os.chmod(self.tmp, 0o555)
        self.addCleanup(os.chmod, self.tmp, 0o755)
        self.addCleanup(shutil.rmtree, paths.SING_BOX_RULE_SETS, True)
        if exporters.SNIPPETS.exists():
            exporters.SNIPPETS.unlink()
        patcher = mock.patch.object(clients, "running", return_value=[])
        patcher.start()
        self.addCleanup(patcher.stop)

    def test_sing_box_rule_sets_in_our_folder_and_steps(self):
        code, text = run("export", "sing-box-config", "--install", "-o", str(self.conf))
        self.assertEqual(code, 0, text)
        self.assertEqual(self.conf.read_text(), SING_BOX_CONFIG)   # left alone
        for name in singbox.RULE_SETS:
            self.assertTrue((paths.SING_BOX_RULE_SETS / f"{name}.json").exists())
        self.assertIn("is not writable by you", text)
        self.assertIn("① Under outbounds:", text)
        self.assertIn("③ At the TOP of route.rules:", text)
        self.assertIn(f'"path": "{paths.SING_BOX_RULE_SETS / "nju-vpn.json"}"', text)
        self.assertIn('{"rule_set": "nju-direct", "outbound": "direct-out"},', text)   # the config's direct
        self.assertEqual(remembered_dict(), {"sing-box-config": exporters.INSTALL + str(self.conf)})
        _, listing = run("export", "--list")
        self.assertIn("(merged by hand once)", listing)
        # policy changes: the rule sets follow, nothing to merge
        (paths.SING_BOX_RULE_SETS / "nju-vpn.json").write_text("{}")
        with mock.patch.object(exporters, "notify") as notify:
            exporters.refresh_exports(quiet=True)
            notify.assert_not_called()
            self.assertIn("ip_cidr", (paths.SING_BOX_RULE_SETS / "nju-vpn.json").read_text())
            config.set_options({"export.proxy_name": "NJU2"})   # the merged part changes
            self.addCleanup(config.set_options, {"export.proxy_name": "NJUConnect"})
            exporters.refresh_exports(quiet=True)
        self.assertTrue(any("merge it again" in c.args[0] for c in notify.call_args_list))

    def test_xray_prints_and_is_not_kept(self):
        self.conf.chmod(0o644)
        os.chmod(self.tmp, 0o755)
        self.conf.write_text('{"outbounds": [{"tag": "proxy", "protocol": "vless"}]}')
        os.chmod(self.conf, 0o444)
        os.chmod(self.tmp, 0o555)
        with mock.patch.object(xray, "xray_binary", return_value=None):
            code, text = run("export", "xray", "--install", "-o", str(self.conf))
        self.assertEqual(code, 0, text)
        self.assertIn("② At the TOP of routing.rules:", text)
        self.assertIn('"ruleTag": "nju-connect"', text)
        self.assertIn("Not kept up to date", text)
        self.assertEqual(remembered_dict(), {})   # nothing the service could keep up to date


